import {
  pgTable,
  uuid,
  text,
  boolean,
  date,
  integer,
  numeric,
  time,
  timestamp,
  index,
  uniqueIndex,
} from 'drizzle-orm/pg-core';
import { tenants } from './tenants';
import { tenantMemberships } from './auth';
import { studentStatusEnum, sexEnum } from './enums';
import {
  studyPrograms,
  curricula,
  courses,
  academicPeriods,
  rooms,
} from './academic-master';

export const students = pgTable(
  'students',
  {
    id: uuid('id').primaryKey(),
    tenantId: uuid('tenant_id')
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    membershipId: uuid('membership_id')
      .notNull()
      .references(() => tenantMemberships.id, { onDelete: 'cascade' }),
    programId: uuid('program_id')
      .notNull()
      .references(() => studyPrograms.id),
    curriculumId: uuid('curriculum_id').references(() => curricula.id),
    nim: text('nim').notNull(),
    fullName: text('full_name').notNull(),
    entryYear: integer('entry_year').notNull(),
    entryRoute: text('entry_route'),
    status: studentStatusEnum('status').notNull().default('ACTIVE'),
    // ── Biodata wajib feeder (DATA_MODEL §11.2) ──
    sex: sexEnum('sex'),
    birthPlace: text('birth_place'),
    birthDate: date('birth_date'),
    citizenship: text('citizenship').notNull().default('WNI'),
    religion: text('religion'),
    childOrder: integer('child_order'),
    mobilePhone: text('mobile_phone'),
    personalEmail: text('personal_email'),
    fundingSource: text('funding_source'), // MANDIRI | BEASISWA | BIA_ADIK | KERJA_SAMA | LAIN
    photoUrl: text('photo_url'),
    pddiktiIdPpd: uuid('pddikti_id_pd'),
    nisn: text('nisn'),
    feederStatusCode: text('feeder_status_code').notNull().default('1'), // 1 AKTIF..5 LULUS
  },
  (table) => ({
    tenantNimUnique: uniqueIndex('uq_students_nim').on(table.tenantId, table.nim),
    tenantMembershipUnique: uniqueIndex('uq_students_membership').on(
      table.tenantId,
      table.membershipId
    ),
    programIdx: index('idx_students_program').on(table.tenantId, table.programId, table.status),
  })
);

export const classes = pgTable(
  'classes',
  {
    id: uuid('id').primaryKey(),
    tenantId: uuid('tenant_id')
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    programId: uuid('program_id')
      .notNull()
      .references(() => studyPrograms.id),
    periodId: uuid('period_id')
      .notNull()
      .references(() => academicPeriods.id),
    courseId: uuid('course_id')
      .notNull()
      .references(() => courses.id),
    name: text('name').notNull(), // 'Kelas A', 'Kelas B'
    capacity: integer('capacity').notNull(),
    enrolledCount: integer('enrolled_count').notNull().default(0),
    status: text('status').notNull().default('OPEN'), // OPEN | CLOSED | CANCELLED
    deliveryMode: text('delivery_mode').notNull().default('ONSITE'), // ONSITE | ONLINE_SYNC | ONLINE_ASYNC
    virtualMeetingProvider: text('virtual_meeting_provider'), // ZOOM | GOOGLE_MEET | TEAMS | BUILTIN_LMS
    virtualMeetingUrl: text('virtual_meeting_url'),
    isAutoGenerated: boolean('is_auto_generated').notNull().default(false),
    parentClassId: uuid('parent_class_id'),
  },
  (table) => ({
    classUnique: uniqueIndex('uq_classes_course_name').on(
      table.tenantId,
      table.periodId,
      table.courseId,
      table.name
    ),
    periodProgramIdx: index('idx_classes_open').on(table.tenantId, table.periodId, table.programId),
  })
);

export const classAssignments = pgTable(
  'class_assignments',
  {
    id: uuid('id').primaryKey(),
    tenantId: uuid('tenant_id')
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    classId: uuid('class_id')
      .notNull()
      .references(() => classes.id, { onDelete: 'cascade' }),
    lecturerMembershipId: uuid('lecturer_membership_id')
      .notNull()
      .references(() => tenantMemberships.id, { onDelete: 'cascade' }),
    roleInClass: text('role_in_class').notNull(), // COORDINATOR | LECTURER | LAB_ASSIST | EXAMINER | ADVISER
  },
  (table) => ({
    classLecturerUnique: uniqueIndex('uq_class_assignments').on(
      table.classId,
      table.lecturerMembershipId,
      table.roleInClass
    ),
  })
);

export const classSchedules = pgTable(
  'class_schedules',
  {
    id: uuid('id').primaryKey(),
    tenantId: uuid('tenant_id')
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    classId: uuid('class_id')
      .notNull()
      .references(() => classes.id, { onDelete: 'cascade' }),
    roomId: uuid('room_id').references(() => rooms.id),
    dayOfWeek: integer('day_of_week').notNull(), // 1=Senin ... 7=Minggu
    startTime: time('start_time').notNull(),
    endTime: time('end_time').notNull(),
  },
  (table) => ({
    scheduleClassUnique: uniqueIndex('uq_class_schedules').on(
      table.classId,
      table.dayOfWeek,
      table.startTime
    ),
    roomDayTimeIdx: index('idx_schedules_lookup').on(
      table.tenantId,
      table.roomId,
      table.dayOfWeek,
      table.startTime,
      table.endTime
    ),
  })
);

export const classSessions = pgTable(
  'class_sessions',
  {
    id: uuid('id').primaryKey(),
    tenantId: uuid('tenant_id')
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    classId: uuid('class_id')
      .notNull()
      .references(() => classes.id, { onDelete: 'cascade' }),
    heldOn: date('held_on').notNull(),
    seq: integer('seq').notNull(), // Pertemuan 1 s.d. 16
    topic: text('topic'),
    deliveryType: text('delivery_type').notNull().default('ONSITE'), // ONSITE | SYNC_LIVE | ASYNC_MODULE
    virtualRoomUrl: text('virtual_room_url'),
    durationMinutes: integer('duration_minutes').notNull().default(100),
    isAttendanceOpen: boolean('is_attendance_open').notNull().default(false),
  },
  (table) => ({
    sessionSeqUnique: uniqueIndex('uq_class_sessions_seq').on(table.classId, table.seq),
  })
);

export const classWaitlists = pgTable(
  'class_waitlists',
  {
    id: uuid('id').primaryKey(),
    tenantId: uuid('tenant_id')
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    academicPeriodId: uuid('academic_period_id')
      .notNull()
      .references(() => academicPeriods.id),
    courseId: uuid('course_id')
      .notNull()
      .references(() => courses.id),
    targetClassId: uuid('target_class_id').references(() => classes.id),
    studentId: uuid('student_id')
      .notNull()
      .references(() => students.id),
    queueNumber: integer('queue_number').notNull(),
    heldCredits: numeric('held_credits', { precision: 4, scale: 1 }).notNull(),
    status: text('status').notNull().default('WAITING'), // WAITING | PROMOTED | EXPIRED | CANCELLED
    promotedClassId: uuid('promoted_class_id').references(() => classes.id),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    waitlistUnique: uniqueIndex('uq_waitlists_student_course').on(
      table.tenantId,
      table.academicPeriodId,
      table.courseId,
      table.studentId
    ),
    queueIdx: index('idx_waitlists_queue').on(
      table.tenantId,
      table.academicPeriodId,
      table.courseId,
      table.status,
      table.queueNumber
    ),
  })
);
